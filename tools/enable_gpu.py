#!/usr/bin/env python3
"""Enable Flutter GPU for the Android release and debug application."""
from pathlib import Path

manifest = Path("android/app/src/main/AndroidManifest.xml")
if not manifest.exists():
    raise SystemExit("AndroidManifest.xml was not generated by Flutter.")

text = manifest.read_text(encoding="utf-8")
marker = "io.flutter.embedding.android.EnableFlutterGPU"
metadata = '''        <meta-data
            android:name="io.flutter.embedding.android.EnableFlutterGPU"
            android:value="true" />'''
if marker not in text:
    app_start = text.find("<application")
    if app_start < 0:
        raise SystemExit("AndroidManifest.xml has no <application> element.")
    app_end = text.find(">", app_start)
    if app_end < 0:
        raise SystemExit("AndroidManifest.xml has an invalid <application> element.")
    text = text[:app_end + 1] + "\n" + metadata + text[app_end + 1:]
manifest.write_text(text, encoding="utf-8")
print("Flutter GPU enabled.")
